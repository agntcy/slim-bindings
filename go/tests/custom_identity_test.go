// testPair is a certificate (PEM and parsed) with the private key that goes with it.
type testPair struct {
	pem  string
	cert *x509.Certificate
	key  *ecdsa.PrivateKey
}

func parseCertPEM(t *testing.T, text string) *x509.Certificate {
	t.Helper()
	block, _ := pem.Decode([]byte(text))
	if block == nil {
		t.Fatal("no PEM block")
	}
	cert, err := x509.ParseCertificate(block.Bytes)
	if err != nil {
		t.Fatal(err)
	}
	return cert
}

// The test PKI, generated once per run: a CA, and the certificates of alice and bob
// (CN = org/example/alice, org/example/bob) issued by it.
var (
	pkiMu    sync.Mutex
	pkiCA    *testCA
	pkiPairs map[string]*testPair
)

func testPKI(t *testing.T) (*testCA, map[string]*testPair) {
	t.Helper()
	pkiMu.Lock()
	defer pkiMu.Unlock()
	if pkiCA == nil {
		ca := newTestCA(t, "SLIM test CA")
		notBefore, notAfter := time.Now().Add(-time.Hour), time.Now().Add(24*time.Hour)
		pkiPairs = map[string]*testPair{
			"alice": ca.issue(t, "org/example/alice", notBefore, notAfter),
			"bob":   ca.issue(t, "org/example/bob", notBefore, notAfter),
		}
		pkiCA = ca
	}
	return pkiCA, pkiPairs
}

// loadCA is the CA of the test PKI.
func loadCA(t *testing.T) *x509.Certificate {
	t.Helper()
	ca, _ := testPKI(t)
	return ca.cert
}

// readCertFile is the PEM certificate of the test PKI's CA ("ca"), alice or bob.
func readCertFile(t *testing.T, name string) string {
	t.Helper()
	if name == "ca" {
		return string(pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: loadCA(t).Raw}))
	}
	return loadTestPair(t, name).pem
}

// loadTestPair is the certificate and key of alice or bob.
func loadTestPair(t *testing.T, name string) *testPair {
	t.Helper()
	_, pairs := testPKI(t)
	pair, ok := pairs[name]
	if !ok {
		t.Fatalf("no test certificate %q", name)
	}
	return pair
}

// testCA is a CA generated by a test, to issue leaves the verifiers do or do not trust.
type testCA struct {
	cert *x509.Certificate
	key  *ecdsa.PrivateKey
}

func newTestCA(t *testing.T, name string) *testCA {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	template := &x509.Certificate{
		SerialNumber:          big.NewInt(1),
		Subject:               pkix.Name{CommonName: name},
		NotBefore:             time.Now().Add(-time.Hour),
		NotAfter:              time.Now().Add(time.Hour),
		IsCA:                  true,
		BasicConstraintsValid: true,
		KeyUsage:              x509.KeyUsageCertSign,
	}
	der, err := x509.CreateCertificate(rand.Reader, template, template, &key.PublicKey, key)
	if err != nil {
		t.Fatal(err)
	}
	cert, err := x509.ParseCertificate(der)
	if err != nil {
		t.Fatal(err)
	}
	return &testCA{cert: cert, key: key}
}

// issue signs a leaf with the given validity period.
func (ca *testCA) issue(t *testing.T, commonName string, notBefore, notAfter time.Time) *testPair {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	template := &x509.Certificate{
		SerialNumber: big.NewInt(2),
		Subject:      pkix.Name{CommonName: commonName},
		NotBefore:    notBefore,
		NotAfter:     notAfter,
		KeyUsage:     x509.KeyUsageDigitalSignature,
	}
	der, err := x509.CreateCertificate(rand.Reader, template, ca.cert, &key.PublicKey, ca.key)
	if err != nil {
		t.Fatal(err)
	}
	cert, err := x509.ParseCertificate(der)
	if err != nil {
		t.Fatal(err)
	}
	text := string(pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}))
	return &testPair{pem: text, cert: cert, key: key}
}

// newUntrustedPair generates a CA the verifiers do not trust and a leaf signed by it.
func newUntrustedPair(t *testing.T, commonName string) *testPair {
	t.Helper()
	return newTestCA(t, "untrusted-ca").issue(t, commonName, time.Now().Add(-time.Hour), time.Now().Add(time.Hour))
}

// sec1 is the public key of a certificate as an uncompressed SEC1 point.
func sec1(t *testing.T, cert *x509.Certificate) []byte {
	t.Helper()
	k, err := cert.PublicKey.(*ecdsa.PublicKey).ECDH()
	if err != nil {
		t.Fatal(err)
	}
	return k.Bytes()
}

// callCounts counts how often SLIM calls the methods of a custom identity object. SLIM
// calls from its own threads, hence the mutex.
type callCounts struct {
	mu sync.Mutex
	m  map[string]int
}

func (c *callCounts) inc(method string) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if c.m == nil {
		c.m = map[string]int{}
	}
	c.m[method]++
}

func (c *callCounts) get(method string) int {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.m[method]
}

func (c *callCounts) snapshot() map[string]int {
	c.mu.Lock()
	defer c.mu.Unlock()
	out := make(map[string]int, len(c.m))
	for k, v := range c.m {
		out[k] = v
	}
	return out
}

// certProvider is an IdentityProvider implemented in Go. Its token is the certificate in
// PEM form and its signing keys are the certificate's key pair (raw 32-byte secret scalar,
// uncompressed SEC1 public key), so SLIM never installs its own.
type certProvider struct {
	calls callCounts
	pair  *testPair
	keys  slim.SignatureKeys
}

func newCertProvider(t *testing.T, pair *testPair) *certProvider {
	t.Helper()
	return &certProvider{
		pair: pair,
		keys: slim.SignatureKeys{
			SecretKey: pair.key.D.FillBytes(make([]byte, 32)),
			PublicKey: sec1(t, pair.cert),
		},
	}
}

func (p *certProvider) Initialize() error {
	p.calls.inc("Initialize")
	return nil
}

func (p *certProvider) GetToken() (string, error) {
	p.calls.inc("GetToken")
	return p.pair.pem, nil
}

func (p *certProvider) GetId() (string, error) {
	p.calls.inc("GetId")
	return p.pair.cert.Subject.CommonName, nil
}

func (p *certProvider) GetSignatureKeys() (slim.SignatureKeys, error) {
	p.calls.inc("GetSignatureKeys")
	return p.keys, nil
}

func (p *certProvider) MlsSignatureKeysInstalled() (bool, error) {
	p.calls.inc("MlsSignatureKeysInstalled")
	return true, nil
}

func (p *certProvider) SetSignatureKeys(privateKey []byte, publicKey []byte) error {
	p.calls.inc("SetSignatureKeys")
	return slim.NewIdentityCallbackErrorFailed("the signing key is the certificate's key and cannot be replaced")
}

// No persistence.
func (p *certProvider) ExportIdentity() (*slim.IdentityExport, error) { return nil, nil }
func (p *certProvider) HoldsLongTermSigningKey() (bool, error)        { return true, nil }
func (p *certProvider) RestoreIdentity(slim.IdentityExport) error     { return nil }

// certVerifier is an IdentityVerifier implemented in Go. It accepts tokens that are
// certificates issued by the trusted CA, and exposes their claims. Trust anchor only: no
// revocation checking.
type certVerifier struct {
	calls callCounts

	mu       sync.Mutex
	roots    *x509.CertPool
	verified []string
}

func newCertVerifier(ca *x509.Certificate) *certVerifier {
	roots := x509.NewCertPool()
	roots.AddCert(ca)
	return &certVerifier{roots: roots}
}

func (v *certVerifier) parse(token string) (*x509.Certificate, error) {
	fail := func(format string, args ...any) (*x509.Certificate, error) {
		return nil, slim.NewIdentityCallbackErrorFailed(fmt.Sprintf(format, args...))
	}
	block, rest := pem.Decode([]byte(token))
	if block == nil || block.Type != "CERTIFICATE" {
		return fail("malformed token: no PEM certificate")
	}
	if len(bytes.TrimSpace(rest)) != 0 {
		return fail("malformed token: trailing data")
	}
	cert, err := x509.ParseCertificate(block.Bytes)
	if err != nil {
		return fail("malformed token: %v", err)
	}
	if _, err := cert.Verify(x509.VerifyOptions{
		Roots:       v.roots,
		CurrentTime: time.Now(),
		KeyUsages:   []x509.ExtKeyUsage{x509.ExtKeyUsageAny},
	}); err != nil {
		return fail("certificate not trusted: %v", err)
	}
	if cert.IsCA {
		return fail("a CA certificate cannot be used as an identity")
	}
	key, ok := cert.PublicKey.(*ecdsa.PublicKey)
	if !ok || key.Curve != elliptic.P256() {
		return fail("certificate key is not ECDSA P-256")
	}
	cns := 0
	for _, name := range cert.Subject.Names {
		if name.Type.String() == "2.5.4.3" {
			cns++
		}
	}
	if cns != 1 {
		return fail("the certificate subject must have exactly one common name")
	}
	return cert, nil
}

func (v *certVerifier) sec1(cert *x509.Certificate) ([]byte, error) {
	k, err := cert.PublicKey.(*ecdsa.PublicKey).ECDH()
	if err != nil {
		return nil, slim.NewIdentityCallbackErrorFailed(err.Error())
	}
	return k.Bytes(), nil
}

func (v *certVerifier) Initialize() error {
	v.calls.inc("Initialize")
	return nil
}

func (v *certVerifier) VerifyAsync(token string) error {
	v.calls.inc("VerifyAsync")
	return v.verify(token)
}

func (v *certVerifier) Verify(token string) error {
	v.calls.inc("Verify")
	return v.verify(token)
}

func (v *certVerifier) verify(token string) error {
	cert, err := v.parse(token)
	if err != nil {
		return err
	}
	v.mu.Lock()
	defer v.mu.Unlock()
	v.verified = append(v.verified, cert.Subject.CommonName)
	return nil
}

func (v *certVerifier) GetClaims(token string) (string, error) {
	v.calls.inc("GetClaims")
	cert, err := v.parse(token)
	if err != nil {
		return "", err
	}
	claims, err := json.Marshal(map[string]string{"sub": cert.Subject.CommonName})
	return string(claims), err
}

func (v *certVerifier) GetPublicKey(token string) ([]byte, error) {
	v.calls.inc("GetPublicKey")
	cert, err := v.parse(token)
	if err != nil {
		return nil, err
	}
	return v.sec1(cert)
}

func (v *certVerifier) GetSubject(token string) (string, error) {
	v.calls.inc("GetSubject")
	cert, err := v.parse(token)
	if err != nil {
		return "", err
	}
	return cert.Subject.CommonName, nil
}

func (v *certVerifier) VerifyKeyBinding(token string, publicKey []byte) error {
	v.calls.inc("VerifyKeyBinding")
	cert, err := v.parse(token)
	if err != nil {
		return err
	}
	bound, err := v.sec1(cert)
	if err != nil {
		return err
	}
	if !bytes.Equal(bound, publicKey) {
		return slim.NewIdentityCallbackErrorPublicKeyMismatch("token bound to another key")
	}
	return nil
}

func (v *certVerifier) verifiedSubjects() []string {
	v.mu.Lock()
	defer v.mu.Unlock()
	return append([]string(nil), v.verified...)
}

// TestCustomIdentity runs a request/reply between two apps that use a Go identity, with
// and without MLS, and checks that SLIM really called the Go code.
func TestCustomIdentity(t *testing.T) {
	for _, mls := range []bool{false, true} {
		t.Run(fmt.Sprintf("mls=%v", mls), func(t *testing.T) { testCustomIdentity(t, mls) })
	}
}

func testCustomIdentity(t *testing.T, mls bool) {
	slim.InitializeWithDefaults()

	// The apps of the subtests share the global service, and a second pair of apps with
	// the names of an earlier pair (even a destroyed one) cannot reach each other, so each
	// subtest has its own names. The certificates are the ones of alice and bob.
	suffix := fmt.Sprintf("-mls-%v", mls)
	senderName := slim.NewName("org", "example", "alice"+suffix)
	receiverName := slim.NewName("org", "example", "bob"+suffix)
	senderCN := loadTestPair(t, "alice").cert.Subject.CommonName

	ca := loadCA(t)
	senderProvider := newCertProvider(t, loadTestPair(t, "alice"))
	senderVerifier := newCertVerifier(ca)
	receiverProvider := newCertProvider(t, loadTestPair(t, "bob"))
	receiverVerifier := newCertVerifier(ca)

	sender, err := slim.AppNewWithCustomIdentity(senderName, senderProvider, senderVerifier, slim.DirectionBidirectional)
	if err != nil {
		t.Fatalf("create sender: %v", err)
	}
	defer sender.Destroy()
	receiver, err := slim.AppNewWithCustomIdentity(receiverName, receiverProvider, receiverVerifier, slim.DirectionBidirectional)
	if err != nil {
		t.Fatalf("create receiver: %v", err)
	}
	defer receiver.Destroy()

	// Initialize is called once per identity object while the app is created, and none of
	// the session-time methods has been called yet. GetToken is the exception: SLIM
	// fetches a token while it creates the app, so its count is only a baseline.
	sessionMethods := []string{"GetSignatureKeys", "MlsSignatureKeysInstalled", "SetSignatureKeys"}
	for name, p := range map[string]*certProvider{"sender": senderProvider, "receiver": receiverProvider} {
		if n := p.calls.get("Initialize"); n != 1 {
			t.Fatalf("%s provider: Initialize called %d times, want 1", name, n)
		}
		for _, m := range sessionMethods {
			if n := p.calls.get(m); n != 0 {
				t.Fatalf("%s provider: %s called %d times before any session", name, m, n)
			}
		}
	}
	for name, v := range map[string]*certVerifier{"sender": senderVerifier, "receiver": receiverVerifier} {
		if n := v.calls.get("Initialize"); n != 1 {
			t.Fatalf("%s verifier: Initialize called %d times, want 1", name, n)
		}
		for _, m := range []string{"Verify", "VerifyAsync", "GetPublicKey", "VerifyKeyBinding"} {
			if n := v.calls.get(m); n != 0 {
				t.Fatalf("%s verifier: %s called %d times before any session", name, m, n)
			}
		}
	}

	tokensBefore := map[*certProvider]int{
		senderProvider:   senderProvider.calls.get("GetToken"),
		receiverProvider: receiverProvider.calls.get("GetToken"),
	}

	request := []byte("thisistherequest")
	response := []byte("thisistheresponse")

	served := make(chan error, 1)
	go func() {
		timeout := 10 * time.Second
		session, err := receiver.ListenForSession(&timeout)
		if err != nil {
			served <- fmt.Errorf("listen: %w", err)
			return
		}
		defer session.Destroy()
		received, err := session.GetMessage(&timeout)
		if err != nil {
			served <- fmt.Errorf("get message: %w", err)
			return
		}
		if string(received.Payload) != string(request) {
			served <- fmt.Errorf("unexpected request %q", received.Payload)
			return
		}
		served <- session.PublishToAndWait(received.Context, response, nil, nil)
	}()

	var mlsSettings *slim.MlsSettings
	if mls {
		mlsSettings = &slim.MlsSettings{HeaderIntegrityValidationPercent: 100}
	}
	session, err := sender.CreateSessionAndWait(slim.SessionConfig{
		SessionType: slim.SessionTypePointToPoint,
		MlsSettings: mlsSettings,
	}, receiverName)
	if err != nil {
		t.Fatalf("create session: %v", err)
	}
	defer session.Destroy()

	if err := session.PublishAndWait(request, nil, nil); err != nil {
		t.Fatalf("publish: %v", err)
	}
	timeout := 10 * time.Second
	reply, err := session.GetMessage(&timeout)
	if err != nil {
		t.Fatalf("get reply: %v", err)
	}
	if string(reply.Payload) != string(response) {
		t.Fatalf("unexpected reply %q", reply.Payload)
	}
	if err := <-served; err != nil {
		t.Fatalf("receiver: %v", err)
	}

	// SLIM verified the peer's token with our Go verifier.
	found := false
	for _, subject := range receiverVerifier.verifiedSubjects() {
		if subject == senderCN {
			found = true
		}
	}
	if !found {
		t.Fatalf("receiver verifier never saw %s: %v", senderCN, receiverVerifier.verifiedSubjects())
	}

	// What SLIM called, and for what (the bounds are lower ones: SLIM may call more often).
	//   provider.GetToken                  the token it sends to peers, and the identity of the app
	//   provider.GetSignatureKeys          the key pair that signs the session's MLS messages
	//   verifier.Verify                    the peer's token (VerifyAsync is not used on this path)
	//   verifier.GetPublicKey              the signing public key of the peer (the certificate's)
	// With MLS only:
	//   provider.MlsSignatureKeysInstalled whether SLIM still has to install its MLS key pair (no)
	//   verifier.VerifyKeyBinding          that the peer's token is bound to its MLS key
	//   verifier.GetSubject                the peer's identity
	// Never: provider.SetSignatureKeys, the keys are the certificate's.
	atLeast := func(who string, calls *callCounts, method string, min int) {
		t.Helper()
		if n := calls.get(method); n < min {
			t.Errorf("%s: %s called %d times, want at least %d (all: %v)", who, method, n, min, calls.snapshot())
		}
	}
	exactly := func(who string, calls *callCounts, method string, want int) {
		t.Helper()
		if n := calls.get(method); n != want {
			t.Errorf("%s: %s called %d times, want %d (all: %v)", who, method, n, want, calls.snapshot())
		}
	}
	for who, p := range map[string]*certProvider{"sender provider": senderProvider, "receiver provider": receiverProvider} {
		if n := p.calls.get("GetToken"); n <= tokensBefore[p] {
			t.Errorf("%s: GetToken not called by the session (%d calls, %d before it)", who, n, tokensBefore[p])
		}
		atLeast(who, &p.calls, "GetSignatureKeys", 1)
		exactly(who, &p.calls, "Initialize", 1)
		if mls {
			atLeast(who, &p.calls, "MlsSignatureKeysInstalled", 1)
		} else {
			exactly(who, &p.calls, "MlsSignatureKeysInstalled", 0)
		}
		// The keys are the certificate's, so SLIM never replaces them.
		exactly(who, &p.calls, "SetSignatureKeys", 0)
	}
	for who, v := range map[string]*certVerifier{"sender verifier": senderVerifier, "receiver verifier": receiverVerifier} {
		atLeast(who, &v.calls, "Verify", 1)
		atLeast(who, &v.calls, "GetPublicKey", 1)
		exactly(who, &v.calls, "Initialize", 1)
		if mls {
			atLeast(who, &v.calls, "VerifyKeyBinding", 1)
			atLeast(who, &v.calls, "GetSubject", 1)
		} else {
			exactly(who, &v.calls, "VerifyKeyBinding", 0)
		}
	}
}

// TestCustomIdentityRejectsUntrustedCertificate checks that a verifier that rejects the
// sender's certificate stops the session from being established.
func TestCustomIdentityRejectsUntrustedCertificate(t *testing.T) {
	slim.InitializeWithDefaults()

	senderName := slim.NewName("org", "example", "mallory")
	receiverName := slim.NewName("org", "example", "bob-untrusted")

	ca := loadCA(t)
	// The sender's certificate is signed by a CA the receiver does not trust.
	sender, err := slim.AppNewWithCustomIdentity(senderName,
		newCertProvider(t, newUntrustedPair(t, senderName.String())),
		newCertVerifier(ca), slim.DirectionBidirectional)
	if err != nil {
		t.Fatalf("create sender: %v", err)
	}
	defer sender.Destroy()
	receiver, err := slim.AppNewWithCustomIdentity(receiverName,
		newCertProvider(t, loadTestPair(t, "bob")),
		newCertVerifier(ca), slim.DirectionBidirectional)
	if err != nil {
		t.Fatalf("create receiver: %v", err)
	}
	defer receiver.Destroy()

	session, err := sender.CreateSessionAndWait(slim.SessionConfig{
		SessionType: slim.SessionTypePointToPoint,
		MlsSettings: nil,
	}, receiverName)
	if err == nil {
		session.Destroy()
		t.Fatal("session was established although the receiver rejects the certificate")
	}
}

// TestCustomIdentityVerifierAndProvider exercises the provider and the verifier directly.
func TestCustomIdentityVerifierAndProvider(t *testing.T) {
	ca := loadCA(t)
	verifier := newCertVerifier(ca)
	alice := loadTestPair(t, "alice")
	provider := newCertProvider(t, alice)

	token, err := provider.GetToken()
	if err != nil {
		t.Fatal(err)
	}
	if token != readCertFile(t, "alice") {
		t.Fatal("the token is not the certificate PEM")
	}
	if err := verifier.Verify(token); err != nil {
		t.Fatalf("valid token rejected: %v", err)
	}
	if subject, err := verifier.GetSubject(token); err != nil || subject != "org/example/alice" {
		t.Fatalf("unexpected subject %q: %v", subject, err)
	}
	claims, err := verifier.GetClaims(token)
	if err != nil || claims != `{"sub":"org/example/alice"}` {
		t.Fatalf("unexpected claims %q: %v", claims, err)
	}
	keys, err := provider.GetSignatureKeys()
	if err != nil {
		t.Fatal(err)
	}
	if len(keys.SecretKey) != 32 || len(keys.PublicKey) != 65 || keys.PublicKey[0] != 0x04 {
		t.Fatalf("unexpected key encoding: %d-byte secret, %d-byte public", len(keys.SecretKey), len(keys.PublicKey))
	}
	public, err := verifier.GetPublicKey(token)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(public, keys.PublicKey) || !bytes.Equal(public, sec1(t, alice.cert)) {
		t.Fatal("the verifier's public key is not the provider's and the certificate's")
	}
	if err := verifier.VerifyKeyBinding(token, keys.PublicKey); err != nil {
		t.Fatalf("key binding rejected: %v", err)
	}
	other, _ := newCertProvider(t, loadTestPair(t, "bob")).GetSignatureKeys()
	err = verifier.VerifyKeyBinding(token, other.PublicKey)
	if !errors.Is(err, slim.ErrIdentityCallbackErrorPublicKeyMismatch) {
		t.Fatalf("expected a PublicKeyMismatch error, got %v", err)
	}
	err = provider.SetSignatureKeys([]byte("secret"), []byte("public"))
	if !errors.Is(err, slim.ErrIdentityCallbackErrorFailed) {
		t.Fatalf("expected a Failed error from SetSignatureKeys, got %v", err)
	}
	if installed, err := provider.MlsSignatureKeysInstalled(); err != nil || !installed {
		t.Fatalf("keys not reported as installed (%v, %v)", installed, err)
	}
}

// TestCustomIdentityVerifierRejectsBadTokens checks the verifier turns down what it must.
func TestCustomIdentityVerifierRejectsBadTokens(t *testing.T) {
	ca := loadCA(t)
	verifier := newCertVerifier(ca)
	aliceToken := readCertFile(t, "alice")

	// Flip a character in the middle of the base64 body.
	lines := strings.Split(aliceToken, "\n")
	body := []byte(lines[2])
	if body[10] == 'A' {
		body[10] = 'B'
	} else {
		body[10] = 'A'
	}
	lines[2] = string(body)
	tampered := strings.Join(lines, "\n")

	// A verifier that trusts bob's certificate as its "CA" must not accept alice's.
	bobAsCA := newCertVerifier(loadTestPair(t, "bob").cert)

	own := newTestCA(t, "own-ca")
	ownVerifier := newCertVerifier(own.cert)
	expired := own.issue(t, "org/example/expired", time.Now().Add(-2*time.Hour), time.Now().Add(-time.Hour))
	notYet := own.issue(t, "org/example/future", time.Now().Add(time.Hour), time.Now().Add(2*time.Hour))
	good := own.issue(t, "org/example/good", time.Now().Add(-time.Hour), time.Now().Add(time.Hour))
	if err := ownVerifier.Verify(good.pem); err != nil {
		t.Fatalf("valid certificate of the generated CA rejected: %v", err)
	}

	cases := []struct {
		name     string
		verifier *certVerifier
		token    string
	}{
		{"CA certificate", verifier, readCertFile(t, "ca")},
		{"untrusted CA", verifier, newUntrustedPair(t, "org/example/alice").pem},
		{"not issued by the trusted CA", bobAsCA, aliceToken},
		{"tampered certificate", verifier, tampered},
		{"trailing data", verifier, aliceToken + "garbage"},
		{"expired", ownVerifier, expired.pem},
		{"not yet valid", ownVerifier, notYet.pem},
		{"garbage", verifier, "not a token"},
		{"empty", verifier, ""},
	}
	for _, c := range cases {
		err := c.verifier.Verify(c.token)
		if err == nil {
			t.Errorf("%s: token accepted", c.name)
		} else if !errors.Is(err, slim.ErrIdentityCallbackErrorFailed) {
			t.Errorf("%s: expected a Failed error, got %v", c.name, err)
		}
	}
}
