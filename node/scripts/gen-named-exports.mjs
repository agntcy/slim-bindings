/**
 * Generates node/named-exports.js: an explicit runtime re-export of every VALUE
 * export of the generated bindings, sourced from the runtime-selected platform
 * package via ./binding.js.
 *
 * Why generated: the platform package is chosen at runtime (dynamic import), so
 * ESM's `export * from '<pkg>'` cannot be used to surface named exports on the
 * main `@agntcy/slim-bindings` entry point. We enumerate the value exports here
 * so `import { Channel, RpcError, ... } from '@agntcy/slim-bindings'` resolves
 * at runtime (types come from index.d.ts re-exporting ./types/<ns> for every
 * namespace — keep the two in sync; CI checks it).
 *
 * Usage: node scripts/gen-named-exports.mjs
 * Requires: generated/index.ts and one generated/<ns>.ts per namespace it
 * re-exports (run `task generate` first).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { bindingNamespaces } from './namespaces.mjs';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const nodeDir = path.resolve(scriptDir, '..');
const outPath = path.join(nodeDir, 'named-exports.js');

// The UniFFI namespaces (slim_bindings, slim_rpc, ...) re-exported by
// generated/index.ts; the runtime barrel must surface value exports from all.
let namespaces;
try {
  namespaces = bindingNamespaces(nodeDir);
} catch (err) {
  console.error(`❌ ${err.message}`);
  process.exit(1);
}
const srcPaths = namespaces.map((ns) => path.join(nodeDir, 'generated', `${ns}.ts`));

// Every namespace is required: index.d.ts re-exports all of them, so a missing
// file would ship types for values that are not exported at runtime.
const missingSrc = srcPaths.filter((p) => !fs.existsSync(p));
if (missingSrc.length) {
  console.error(`❌ ${missingSrc.join(', ')} not found. Run \`task generate\` first.`);
  process.exit(1);
}

// Match VALUE exports only (classes, consts, enums, functions). Type-only
// exports (interface/type) are intentionally excluded — they are surfaced via
// index.d.ts and have no runtime representation.
const re = /^export (?:abstract class|class|const|enum|function) ([A-Za-z0-9_$]+)/gm;
const owners = new Map(); // value name -> namespaces exporting it
for (const [i, p] of srcPaths.entries()) {
  for (const [, name] of fs.readFileSync(p, 'utf8').matchAll(re)) {
    const list = owners.get(name) ?? [];
    if (!list.includes(namespaces[i])) list.push(namespaces[i]);
    owners.set(name, list);
  }
}

// A name exported by two namespaces is ambiguous under generated/index.ts's
// `export *` lines: ESM silently drops it from the platform module, so
// `ns.<name>` would be undefined at runtime (and TS reports TS2308 on
// index.d.ts). Fail here instead of shipping an undefined export.
const clashes = [...owners].filter(([, list]) => list.length > 1);
if (clashes.length) {
  console.error('❌ Value exports defined in more than one namespace (ambiguous under `export *`):');
  for (const [name, list] of clashes) console.error(`   ${name}: ${list.join(', ')}`);
  console.error('   Rename one of them in the Rust/UniFFI interface.');
  process.exit(1);
}

const names = [...owners.keys()].sort();

if (names.length === 0) {
  const files = srcPaths.map((p) => path.basename(p)).join(' or ');
  console.error(`❌ No value exports found in ${files} — refusing to write an empty barrel.`);
  process.exit(1);
}

const body = names.map((n) => `export const ${n} = ns.${n};`).join('\n');
const out = `// AUTO-GENERATED by scripts/gen-named-exports.mjs — DO NOT EDIT.
// Runtime named re-exports of the platform binding so that
// \`import { Channel, RpcError, ... } from '@agntcy/slim-bindings'\` works.
// The platform package is selected at runtime (see binding.js), so ESM's
// \`export *\` cannot be used here; each value export is re-bound explicitly.
import { ns } from './binding.js';

${body}
`;

fs.writeFileSync(outPath, out);
console.log(`✅ Wrote named-exports.js with ${names.length} named value exports.`);
